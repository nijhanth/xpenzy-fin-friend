import React, { useEffect, useMemo, useRef, useState } from 'react';
import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import * as z from 'zod';
import { Dialog, DialogContent, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Textarea } from '@/components/ui/textarea';
import { Form, FormControl, FormField, FormItem, FormLabel, FormMessage } from '@/components/ui/form';
import { useFinancial } from '@/contexts/FinancialContext';
import { ReminderCompletionField } from '@/components/forms/ReminderCompletionField';
import { offerReminderCompletion } from '@/lib/reminderCompletion';
import { AccountPicker } from '@/components/forms/AccountPicker';
import { getDefaultAccountId } from '@/lib/financialAccounts';

const transactionSchema = z.object({
  amount: z.number().min(1, 'Amount must be greater than 0'),
  date: z.string().min(1, 'Date is required'),
  notes: z.string().optional(),
  account_id: z.string().nullable().optional()
});

type TransactionFormData = z.infer<typeof transactionSchema>;

interface SavingsTransactionFormProps {
  open: boolean;
  onClose: () => void;
  editingId?: string | null;
  savingsGoalId: string;
  savingsGoalName: string;
  availableBalance: number;
}

export const SavingsTransactionForm: React.FC<SavingsTransactionFormProps> = ({
  open,
  onClose,
  editingId,
  savingsGoalId,
  savingsGoalName,
  availableBalance
}) => {
  const { data, addSavingsTransaction, updateSavingsTransaction } = useFinancial();
  const [relatedReminderId, setRelatedReminderId] = useState('');
  const submitLock = useRef(false);
  const remindersUsedElsewhere = useMemo(() => new Set([
    ...data.expenses.filter(item => item.id !== editingId && item.linkedNoteId).map(item => item.linkedNoteId as string),
    ...data.savingsTransactions.filter(item => item.id !== editingId && item.linked_note_id).map(item => item.linked_note_id as string),
    ...data.investmentTransactions.filter(item => item.linked_note_id).map(item => item.linked_note_id as string),
    ...data.investments.filter(item => item.linked_note_id).map(item => item.linked_note_id as string),
  ]), [data.expenses, data.savingsTransactions, data.investmentTransactions, data.investments, editingId]);

  const form = useForm<TransactionFormData>({
    resolver: zodResolver(transactionSchema),
    defaultValues: {
      amount: 0,
      date: new Date().toISOString().split('T')[0],
      notes: '',
      account_id: getDefaultAccountId(data.accounts)
    }
  });

  useEffect(() => {
    if (open && !editingId) setRelatedReminderId('');
    if (editingId && open) {
      const transaction = data.savingsTransactions.find(t => t.id === editingId);
      if (transaction) {
        setRelatedReminderId(transaction.linked_note_id || '');
        form.reset({
          amount: transaction.amount,
          date: transaction.date,
          notes: transaction.notes || '',
          account_id: transaction.account_id ?? null
        });
      }
    } else if (open && !editingId) {
      form.reset({
        amount: 0,
        date: new Date().toISOString().split('T')[0],
        notes: '',
        account_id: getDefaultAccountId(data.accounts)
      });
    }
  }, [editingId, open, form, data.savingsTransactions, data.accounts]);

  const onSubmit = async (formData: TransactionFormData) => {
    if (submitLock.current) return;
    submitLock.current = true;
    try {
      if (formData.amount > availableBalance) {
        form.setError('amount', { message: `You can add up to ${formatCurrency(availableBalance)} from your estimated bank balance.` });
        return;
      }

      if (editingId) {
        const existingTransaction = data.savingsTransactions.find(transaction => transaction.id === editingId);
        const autoGeneratedNote = existingTransaction?.notes?.startsWith('Added ') && existingTransaction.notes.endsWith(` to ${savingsGoalName}`);
        const saved = await updateSavingsTransaction(editingId, {
          ...formData,
          linked_note_id: relatedReminderId || null,
          account_id: formData.account_id ?? null,
          notes: autoGeneratedNote ? `Added ₹${formData.amount.toLocaleString('en-IN')} to ${savingsGoalName}` : formData.notes,
        });
        if (!saved) return;
        if (relatedReminderId && relatedReminderId !== existingTransaction?.linked_note_id) {
          void offerReminderCompletion(relatedReminderId);
        }
      } else {
        const saved = await addSavingsTransaction({
          savings_goal_id: savingsGoalId,
          amount: formData.amount,
          date: formData.date,
          account_id: formData.account_id ?? null,
          linked_note_id: relatedReminderId || null,
          notes: formData.notes || `Added ₹${formData.amount.toLocaleString('en-IN')} to ${savingsGoalName}`
        });
        if (!saved) return;
        void offerReminderCompletion(relatedReminderId);
      }
      onClose();
    } catch (error) {
      console.error('Savings transaction form error:', error);
    } finally {
      submitLock.current = false;
    }
  };

  const remainingBalance = Math.max(0, availableBalance - Number(form.watch('amount') || 0));

  return (
    <Dialog open={open} onOpenChange={onClose}>
      <DialogContent className="sm:max-w-[425px]">
        <DialogHeader>
          <DialogTitle>
            {editingId ? 'Edit Transaction' : `Add Money to ${savingsGoalName}`}
          </DialogTitle>
        </DialogHeader>
        
        <Form {...form}>
          <form onSubmit={form.handleSubmit(onSubmit)} className="space-y-4">
            <FormField
              control={form.control}
              name="amount"
              render={({ field }) => (
                <FormItem>
                  <div className="flex items-center justify-between gap-2">
                    <FormLabel>Amount (₹)</FormLabel>
                    <Button
                      type="button"
                      variant="link"
                      className="h-auto p-0 text-xs"
                      disabled={availableBalance < 1}
                      onClick={() => form.setValue('amount', availableBalance, { shouldDirty: true, shouldValidate: true })}
                    >
                      Use all available
                    </Button>
                  </div>
                  <FormControl>
                    <Input
                      type="number"
                      placeholder="Enter amount"
                      {...field}
                      value={field.value || ''}
                      onChange={(e) => field.onChange(Number(e.target.value))}
                      min="1"
                      max={availableBalance}
                      step="1"
                    />
                  </FormControl>
                  <p className="text-xs text-muted-foreground">
                    Available to add: {formatCurrency(availableBalance)}. Estimated bank balance after transfer: {formatCurrency(remainingBalance)}.
                  </p>
                  <FormMessage />
                </FormItem>
              )}
            />

            <FormField
              control={form.control}
              name="date"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>Date</FormLabel>
                  <FormControl>
                    <Input type="date" {...field} />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />

            <FormField
              control={form.control}
              name="account_id"
              render={({ field }) => (
                <FormItem>
                  <FormControl>
                    <AccountPicker id="savings-transaction-account" accounts={data.accounts} value={field.value} onChange={field.onChange} />
                  </FormControl>
                  {data.accounts.length > 0 && <p className="text-xs text-muted-foreground">For a transfer between your own accounts, use Settings → Accounts and link the savings goal there instead.</p>}
                </FormItem>
              )}
            />

            <FormField
              control={form.control}
              name="notes"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>Notes (Optional)</FormLabel>
                  <FormControl>
                    <Textarea
                      placeholder="Add any notes about this transaction..."
                      className="resize-none"
                      {...field}
                    />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />

            <ReminderCompletionField value={relatedReminderId} onChange={setRelatedReminderId} refreshKey={open} excludedReminderIds={remindersUsedElsewhere} />

            <div className="flex justify-end space-x-2">
              <Button type="button" variant="outline" onClick={onClose}>
                Cancel
              </Button>
              <Button type="submit" className="bg-savings text-white" disabled={availableBalance < 1 || form.formState.isSubmitting}>
                {form.formState.isSubmitting ? 'Saving…' : editingId ? 'Update Transaction' : 'Add Money'}
              </Button>
            </div>
          </form>
        </Form>
      </DialogContent>
    </Dialog>
  );
};

const formatCurrency = (amount: number) => new Intl.NumberFormat('en-IN', {
  style: 'currency', currency: 'INR', maximumFractionDigits: 0,
}).format(amount);
